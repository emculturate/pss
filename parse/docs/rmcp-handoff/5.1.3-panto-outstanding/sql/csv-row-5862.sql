        cast(alr_student.EAB_ALUMNI_RELATION_IND AS boolean) AS eab_alumni_relation_ind,
        cast(alr_student.EAB_ETHNICITY AS varchar) AS eab_ethnicity,
        cast(alr_student.HISPANIC_IND AS varchar) AS hispanic_ind,
        cast(alr_student.<Ethnicity> AS varchar) AS ethnicity,
        cast(alr_student.CAMPUS_VISIT_CNT AS varchar) AS campus_visit_cnt,
        cast(alr_student.CAMPUS_VISIT_IND AS varchar) AS campus_visit_ind,
