        cast(alr_student.EAB_PREF_GENDER AS varchar) AS eab_pref_gender,
        cast(alr_student.EAB_INTERNATIONAL_IND AS boolean) AS eab_international_ind,
        cast(alr_student.EAB_MILITARY_VETERAN_IND AS boolean) AS eab_military_veteran_ind,
