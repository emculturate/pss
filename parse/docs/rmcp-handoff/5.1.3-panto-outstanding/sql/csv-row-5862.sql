        cast(alr_student.LAST_CAMPUS_VISIT_DT AS timestamp) AS last_campus_visit_dt,
        cast(alr_student.EAB_CAMPUS_VISIT_IND AS boolean) AS eab_campus_visit_ind,
        cast(alr_student.MAIL_OPTOUT_IND AS varchar) AS mail_optout_ind,
        cast(alr_student.EAB_MAIL_OPTOUT_IND AS boolean) AS eab_mail_optout_ind,
        cast(alr_student.EMAIL_OPTOUT_IND AS varchar) AS email_optout_ind,
        cast(alr_student.PHONE_OPTOUT_IND AS varchar) AS phone_optout_ind,
        cast(alr_student.SMS_OPTIN_IND AS varchar) AS sms_optin_ind,
        cast(alr_student.SMS_OPTOUT_IND AS varchar) AS sms_optout_ind,
        cast(alr_student.EAB_EMAIL_OPTOUT_IND AS boolean) AS eab_email_optout_ind,
        cast(alr_student.EAB_PHONE_OPTOUT_IND AS boolean) AS eab_phone_optout_ind,
        cast(alr_student.EAB_SMS_OPTIN_IND AS boolean) AS eab_sms_optin_ind,
        cast(alr_student.EAB_OPT_OUT_IND AS boolean) AS eab_opt_out_ind,
        cast(alr_student.OPT_OUT_IND AS varchar) AS opt_out_ind,
        cast(alr_student.<Intake Dt> AS timestamp) AS intake_dt
FROM
     <[ALR].[student].{final}> AS alr_student
WHERE alr_student.primary_student_id != '' AND alr_student.primary_student_id IS NOT NULL
UNION
SELECT
        par__student.primary_student_id AS primary_student_id,
        par__student.sis_student_id AS sis_student_id,
        par__student.eab_student_id AS eab_student_id,
        par__student.crm_student_id AS crm_student_id,
        par__student.other_student_id AS other_student_id,
        par__student.fname AS fname,
        par__student.mname AS mname,
        par__student.lname AS lname,
        par__student.suffix AS suffix,
        par__student.prefix AS prefix,
        par__student.preferred_fname AS preferred_fname,
        par__student.us_citizenship_status AS us_citizenship_status,
        par__student.international_ind AS international_ind,
        par__student.birth_dt AS birth_dt,
        par__student.gender AS gender,
        par__student.pref_gender AS pref_gender,
        par__student.religious_affiliation AS religious_affiliation,
        par__student.hs_grad_year AS hs_grad_year,
        par__student.origin_source AS origin_source,
        par__student.origin_source_dt AS origin_source_dt,
        par__student.first_gen_ind AS first_gen_ind,
        par__student.military_service_status AS military_service_status,
