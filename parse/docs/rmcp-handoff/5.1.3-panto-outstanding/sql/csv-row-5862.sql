        par__student.eab_phone_optout_ind AS eab_phone_optout_ind,
        par__student.eab_sms_optin_ind AS eab_sms_optin_ind,
        par__student.eab_opt_out_ind AS eab_opt_out_ind,
        par__student.opt_out_ind AS opt_out_ind,
        par__student.intake_dt AS intake_dt
FROM
     PDP_ALR_V2.par__student AS par__student
LEFT JOIN
     <[ALR].[student].{final}> AS alr__student
   ON   
     coalesce(par__student.primary_student_id, '') = coalesce(alr__student.<Primary Student ID>, '')
WHERE 
     alr__student.<Primary Student ID> IS NULL