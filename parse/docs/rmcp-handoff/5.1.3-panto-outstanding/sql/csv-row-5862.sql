SELECT
        cast(alr_student.<Primary Student ID> AS varchar ) AS primary_student_id,
        cast(alr_student.<SIS Student ID> AS varchar) AS sis_student_id,
        cast(alr_student.<EAB Student ID> AS varchar) AS eab_student_id,
        cast(alr_student.<CRM Student ID> AS varchar) AS crm_student_id,
        cast(alr_student.<Other Student ID> AS varchar) AS other_student_id,
        cast(alr_student.FNAME AS varchar) AS fname,
        cast(alr_student.MNAME AS varchar) AS mname,
        cast(alr_student.LNAME AS varchar) AS lname,
        cast(alr_student.<Suffix> AS varchar) AS suffix,
        cast(alr_student.<Prefix> AS varchar) AS prefix,
        cast(alr_student.PREFERRED_FNAME AS varchar) AS preferred_fname,
        cast(alr_student.<US Citizenship Status> AS varchar) AS us_citizenship_status,
        cast(alr_student.INTERNATIONAL_IND AS varchar) AS international_ind,
        cast(alr_student.BIRTH_DT AS timestamp) AS birth_dt,
        cast(alr_student.<Gender> AS varchar) AS gender,
        cast(alr_student.PREF_GENDER AS varchar) AS pref_gender,
